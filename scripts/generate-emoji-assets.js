/**
 * Generate SVG emoji assets for Pip.
 *
 * This script creates simple SVG files for each emoji in the curated set.
 * The SVGs are basic representations using emoji characters rendered as text.
 *
 * Usage: node scripts/generate-emoji-assets.js
 */

import { writeFileSync, mkdirSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

// Import emoji data
const emojisPath = resolve(ROOT, "packages/shared/src/emojis.js");

async function main() {
  const { getAllEmojis } = await import(emojisPath);
  const allEmojis = getAllEmojis();

  const outputDirs = [
    resolve(ROOT, "packages/shared/src/emoji-assets"),
    resolve(ROOT, "apps/client/src/renderer/emoji-assets"),
    resolve(ROOT, "apps/reception/src/renderer/emoji-assets"),
    resolve(ROOT, "apps/echo/src/renderer/emoji-assets"),
  ];

  // Ensure output directories exist
  for (const dir of outputDirs) {
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
    }
  }

  let count = 0;

  for (const emoji of allEmojis) {
    const svg = generateSvg(emoji.char);
    const filename = `${emoji.hex}.svg`;

    for (const dir of outputDirs) {
      writeFileSync(resolve(dir, filename), svg, "utf-8");
    }

    count++;
  }

  // Write a README in the shared assets directory
  const readmePath = resolve(outputDirs[0], "README.md");
  writeFileSync(
    readmePath,
    `# Emoji Assets\n\nAuto-generated SVG emoji assets for Pip.\n\nGenerated by \`scripts/generate-emoji-assets.js\`\n\n${count} emoji SVGs generated.\n`,
    "utf-8"
  );

  console.log(`Generated ${count} emoji SVGs in ${outputDirs.length} directories.`);
}

/**
 * Generate a simple SVG that renders an emoji character as text.
 * This is a lightweight approach - the emoji renders using the system's emoji font.
 */
function generateSvg(char) {
  const codePoint = char.codePointAt(0).toString(16).toUpperCase();
  const width = 128;
  const height = 128;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <text x="50%" y="50%" dominant-baseline="central" text-anchor="middle" font-size="96">${char}</text>
</svg>
`;
}

main().catch((err) => {
  console.error("Failed to generate emoji assets:", err);
  process.exit(1);
});
